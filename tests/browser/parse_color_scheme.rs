#[cfg(test)]
mod passing {
    use monolith::browser::{ColorScheme, parse_color_scheme};

    #[test]
    fn dark() {
        assert_eq!(parse_color_scheme("dark"), Ok(Some(ColorScheme::Dark)));
    }

    #[test]
    fn light_in_any_case() {
        assert_eq!(parse_color_scheme(" Light "), Ok(Some(ColorScheme::Light)));
    }

    #[test]
    fn following_the_system() {
        assert_eq!(parse_color_scheme("auto"), Ok(None));
        assert_eq!(parse_color_scheme("system"), Ok(None));
        assert_eq!(parse_color_scheme(""), Ok(None));
    }
}

