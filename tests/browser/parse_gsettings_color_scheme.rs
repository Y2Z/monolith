#[cfg(test)]
mod passing {
    use monolith::browser::{ColorScheme, parse_gsettings_color_scheme};

    #[test]
    fn dark() {
        assert_eq!(
            parse_gsettings_color_scheme("'prefer-dark'\n"),
            Some(ColorScheme::Dark)
        );
    }

    #[test]
    fn light() {
        assert_eq!(
            parse_gsettings_color_scheme("'default'\n"),
            Some(ColorScheme::Light)
        );
    }
}

