#[cfg(test)]
mod passing {
    use monolith::browser::{ColorScheme, parse_windows_color_scheme};

    #[test]
    fn dark() {
        assert_eq!(
            parse_windows_color_scheme("    AppsUseLightTheme    REG_DWORD    0x0\r\n"),
            Some(ColorScheme::Dark)
        );
    }

    #[test]
    fn light() {
        assert_eq!(
            parse_windows_color_scheme("    AppsUseLightTheme    REG_DWORD    0x1\r\n"),
            Some(ColorScheme::Light)
        );
    }
}

