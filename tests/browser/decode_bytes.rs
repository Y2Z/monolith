#[cfg(test)]
mod passing {
    use monolith::browser::decode_bytes;
    use serde_json::json;

    #[test]
    fn string() {
        assert_eq!(
            decode_bytes(&json!({"type": "string", "value": "body{}"})),
            Some(b"body{}".to_vec())
        );
    }

    #[test]
    fn base64() {
        assert_eq!(
            decode_bytes(&json!({"type": "base64", "value": "/9j/"})),
            Some(vec![0xFF, 0xD8, 0xFF])
        );
    }
}

